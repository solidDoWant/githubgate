package main

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"

	"github.com/vektah/gqlparser/v2/ast"
	"github.com/vektah/gqlparser/v2/parser"
)

// slashParams are the path parameters whose values may contain "/" (a ref,
// a file path, a "base...head" pair). Each matches one or more segments.
var slashParams = map[string]bool{
	"basehead": true,
	"branch":   true,
	"dir":      true,
	"path":     true,
	"ref":      true,
	"tag":      true,
}

// singleSegmentParams are parameters whose names look as if they might hold
// a "/" but were reviewed: GitHub's values for them never contain one.
var singleSegmentParams = map[string]bool{
	"archive_format":         true,
	"branch_policy_id":       true,
	"commit_sha":             true,
	"concurrency_group_name": true,
	"environment_name":       true,
	"file_sha":               true,
	"sha":                    true,
	"subject_digest":         true,
	"tag_sha":                true,
	"tree_sha":               true,
}

// slashReview matches parameter names that must be classified in slashParams
// or singleSegmentParams: a new parameter like these fails generation until
// someone decides whether its values may contain "/".
var slashReview = regexp.MustCompile(`(?i)ref|path|branch|base|head|tag|dir|file|glob|sha|digest|concurrency|environment`)

var httpMethods = map[string]string{
	"get": "GET", "put": "PUT", "post": "POST", "delete": "DELETE", "patch": "PATCH",
}

type restEntry struct {
	method, id, template, slash string
}

// generateREST writes the REST operation catalogue from the description's paths.
// ids maps each path template to its methods (lower case, as in the
// description) and their operation ids.
func generateREST(ids map[string]map[string]string) ([]byte, error) {
	if len(ids) == 0 {
		return nil, fmt.Errorf("the description has no paths")
	}

	var entries []restEntry

	shapes := map[string]string{}

	for template, methods := range ids {
		slash, shape, err := checkTemplate(template)
		if err != nil {
			return nil, err
		}

		for method, id := range methods {
			upper, ok := httpMethods[method]
			if !ok {
				continue
			}

			if id == "" {
				return nil, fmt.Errorf("%s %s has no operation id", upper, template)
			}

			key := upper + " " + shape
			if other, dup := shapes[key]; dup {
				return nil, fmt.Errorf("%s %s and %s have the same shape", upper, template, other)
			}

			shapes[key] = template
			entries = append(entries, restEntry{method: upper, id: id, template: template, slash: slash})
		}
	}

	sort.Slice(entries, func(i, j int) bool {
		if entries[i].template != entries[j].template {
			return entries[i].template < entries[j].template
		}

		return entries[i].method < entries[j].method
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/gen-permissions from github/rest-api-description at commit " +
		descriptionCommit + ". DO NOT EDIT.\n\npackage operations\n\n")
	buf.WriteString("var restCatalogue = []restOperation{\n")

	for _, entry := range entries {
		fmt.Fprintf(&buf, "\t{Method: %q, ID: %q, Template: %q, SlashParam: %q},\n",
			entry.method, entry.id, entry.template, entry.slash)
	}

	buf.WriteString("}\n")

	return format.Source(buf.Bytes())
}

// checkTemplate classifies a path template's parameters. It returns the name
// of its slash parameter (or "") and its shape: the template with every
// parameter replaced, so two templates matching the same paths compare equal.
func checkTemplate(template string) (string, string, error) {
	if !strings.HasPrefix(template, "/") {
		return "", "", fmt.Errorf("path %q does not start with /", template)
	}

	slash := ""

	var shape []string

	segments := strings.Split(strings.TrimPrefix(template, "/"), "/")
	if template == "/" {
		segments = nil
	}

	for _, segment := range segments {
		if segment == "" {
			return "", "", fmt.Errorf("path %q has an empty segment", template)
		}

		if !strings.HasPrefix(segment, "{") {
			if strings.ContainsAny(segment, "{}") {
				return "", "", fmt.Errorf("path %q mixes a parameter and text in one segment", template)
			}

			shape = append(shape, segment)

			continue
		}

		name := strings.TrimSuffix(strings.TrimPrefix(segment, "{"), "}")
		if name == "" || strings.ContainsAny(name, "{}") || !strings.HasSuffix(segment, "}") {
			return "", "", fmt.Errorf("path %q has a malformed parameter %q", template, segment)
		}

		if slash != "" {
			return "", "", fmt.Errorf("path %q has parameter %q after slash parameter %q", template, name, slash)
		}

		switch {
		case slashParams[name]:
			slash = name

			shape = append(shape, "{**}")
		case slashReview.MatchString(name) && !singleSegmentParams[name]:
			return "", "", fmt.Errorf("path %q: parameter %q may contain a slash: add it to slashParams or singleSegmentParams", template, name)
		default:
			shape = append(shape, "{*}")
		}
	}

	return slash, "/" + strings.Join(shape, "/"), nil
}

// generateMutations writes the names of the Mutation type's fields.
func generateMutations(schema string) ([]byte, error) {
	doc, err := parser.ParseSchema(&ast.Source{Name: "schema.graphql", Input: schema})
	if err != nil {
		return nil, fmt.Errorf("parsing the GraphQL schema: %w", err)
	}

	var names []string

	seen := map[string]bool{}

	for _, list := range []ast.DefinitionList{doc.Definitions, doc.Extensions} {
		for _, def := range list {
			if def.Name != "Mutation" {
				continue
			}

			if def.Kind != ast.Object {
				return nil, fmt.Errorf("type Mutation is a %s, not an object", def.Kind)
			}

			for _, field := range def.Fields {
				if seen[field.Name] {
					return nil, fmt.Errorf("mutation %q is defined twice", field.Name)
				}

				seen[field.Name] = true
				names = append(names, field.Name)
			}
		}
	}

	if len(names) == 0 {
		return nil, fmt.Errorf("the GraphQL schema has no Mutation fields")
	}

	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/gen-permissions from octokit/graphql-schema at commit " +
		schemaCommit + ". DO NOT EDIT.\n\npackage operations\n\n")
	buf.WriteString("var mutationCatalogue = map[string]struct{}{\n")

	for _, name := range names {
		fmt.Fprintf(&buf, "\t%q: {},\n", name)
	}

	buf.WriteString("}\n")

	return format.Source(buf.Bytes())
}
